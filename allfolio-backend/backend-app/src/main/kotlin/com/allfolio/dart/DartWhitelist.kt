     * T6에 넣은 이유가 이것이다 — elestock에 없는 서류다.
     */
    const val TIER_INSIDER: Short = 4

    /**
     * 내부에서 [DartReportName.normalize]를 부르지 않는다 — 의도적이다. 정규화를 호출부의
     * 책임으로 남겨야 테스트 `원문을 그대로 넣으면 안 된다 — 정규화를 거쳐야 잡힌다`가
     * "원문을 그대로 넣으면 null"이라는, 원안이 틀렸던 지점을 계속 검증할 수 있다. 여기서
     * 정규화를 흡수하면 그 구분과 테스트 둘 다 의미를 잃는다. 호출처는 Task 8 하나뿐이고
     * 거기서 `normalize` 직후 세 줄 안에 `tierOf`를 부른다.
     */
    fun tierOf(normalized: String): Short? {
        val tier = TIERS.firstOrNull { (_, keywords) ->
            keywords.any { it in normalized }
        }?.first ?: return null

        return if (isAdministrativeHalt(tier, normalized)) null else tier
    }

    /**
     * 거래정지·상장폐지 **말고는 T3가 될 근거가 없는데** 사유가 행정적인 건을 가린다.
     *
     * 두 조건을 모두 봐야 한다. 사유만 보면 `주권매매거래정지 (액면병합 …)`처럼 행정적인
     * 것과, 만에 하나 `횡령·배임` 같은 진짜 위험 키워드가 함께 든 이름을 구분하지 못한다 —
     * 후자는 남아야 한다. 그래서 "T3가 된 근거가 [HALT_OR_DELIST]뿐인가"를 함께 확인한다.
     */
    private fun isAdministrativeHalt(tier: Short, normalized: String): Boolean {
        if (tier != TIER_RISK) return false
        val riskOtherThanHalt = TIERS
            .first { it.first == TIER_RISK }.second
            .filterNot { it in HALT_OR_DELIST }
            .any { it in normalized }
        if (riskOtherThanHalt) return false
        return ADMINISTRATIVE_REASONS.any { it in normalized }
    }

    /**
     * `is_material`은 `material_tier`와 별개 컬럼이다 — 이 함수가 둘의 일관성을 정하는
     * 단일 지점이다. 나중에 누가 `tier != null`로 인라인해 버리면 아래 불변식이 기록 없이
     * 사라지므로 여기 남긴다: Tier 5(정기보고서)도 material은 true다 — 저장·조인은
     * 그대로 되고 기본 정렬에서만 뒤로 간다(설계 5절).
     */
    fun isMaterial(tier: Short?): Boolean = tier != null
}
