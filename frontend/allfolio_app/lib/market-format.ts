/**
 * 시장 화면 숫자 표시 포맷 (AF-104).
 *
 * **자릿수를 화면에서 다시 못 박는다.** 백엔드는 BigDecimal 스케일을 의도적으로 정해
 * `2.7500`·`-1.20`으로 내보내지만, `JSON.parse`가 JS number로 바꾸는 순간 뒤 0이 사라져
 * `2.75`·`-1.2`가 된다. 되살릴 방법이 없으니 표시 시점에 다시 고정하는 수밖에 없다.
 * 시안 규약이 "숫자는 고정폭 + tabular-nums"라, 자릿수가 들쭉날쭉하면 표를 세로로 훑는
 * 것 자체가 안 된다 — `Num` 프리미티브를 쓰는 이유가 통째로 사라진다.
 *
 * **컴포넌트마다 `.toFixed()`를 흩뿌리지 않는다.** 네 군데가 각자 관례를 기르면
 * 같은 열에서 자릿수가 갈린다. 자릿수 규약은 호출부에 적되 함수는 여기 하나만 둔다.
 */

/**
 * 소수 [digits]자리로 고정한 문자열. null/undefined는 대시다 —
 * **0으로 찍으면 안 된다.** "직전 값이 없다"가 "안 움직였다"로, "은행이 취급 안 한다"가
 * "환율이 0원"으로 읽힌다.
 */
export function fixed(n: number | null | undefined, digits: number): string {
  if (n === null || n === undefined) return '-'
  return n.toFixed(digits)
}
