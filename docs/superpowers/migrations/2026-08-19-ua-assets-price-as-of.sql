--
--
-- ## 왜 `last_updated_at`으로 안 되는가
--
-- `ua_assets`에는 이미 `last_updated_at`이 있다. 하지만 그건 **"우리가 언제 썼나"**이고,
-- 여기 필요한 것은 **"그 값이 어느 날짜 시세인가"**다. 둘은 다르다.
--
-- 공공데이터포털 금 시세는 D+1 공표라, 19:30에 도는 평가 배치는 **평일에도** 최소 하루 낡은
-- 값을 쓴다. 연휴 뒤에는 4일까지 벌어진다(2026-08-18 실측: 평가일 78일 중 1일 68% ·
-- 2일 15% · 3일 14% · 4일 3%, 최대 4). 즉 `last_updated_at = 오늘`인데 값은 나흘 전 종가일 수
-- 있고, 그 상태를 화면이 "오늘 기준"이라고 말하면 거짓이 된다.
--
-- 설계 원칙("기준일을 숨기지 않는다")이 요구하는 것이 이 컬럼이다. 화면은 이 값으로
-- "8/14 종가 기준"이라고 적는다.
--
--
-- ## nullable인 이유
--
-- 수동 입력 자산(부동산·차량·전세, 그리고 아직 평가 안 된 금)에는 시세 기준일이 없다.
-- **0이나 오늘 날짜로 채우지 말 것** — "모른다"와 "오늘 시세다"는 다르고, 후자로 채우면
-- 화면이 수동 입력값을 자동 평가된 신선한 값처럼 설명한다.
--
--
-- ## 인덱스를 만들지 않는다
--
-- 이 컬럼으로 조회하는 경로가 없다. 평가 배치는 `type`으로 고르고, 화면은 이미 읽은 행에서
-- 함께 꺼내 쓴다. 나중에 "묵은 자산 찾기" 같은 조회가 생기면 그때 만들 것.

ALTER TABLE ua_assets ADD COLUMN IF NOT EXISTS price_as_of DATE;

COMMENT ON COLUMN ua_assets.price_as_of IS
    '자동 평가된 자산의 시세 기준일. last_updated_at(우리가 쓴 시각)과 다르다 — 금은 D+1 공표라 평일에도 하루 이상 벌어진다. 수동 입력 자산은 NULL';

-- ── 검증 ────────────────────────────────────────────────────────────────────
SELECT
    count(*)                                    AS total_assets,
    count(*) FILTER (WHERE price_as_of IS NULL) AS not_valued_yet
FROM ua_assets;
