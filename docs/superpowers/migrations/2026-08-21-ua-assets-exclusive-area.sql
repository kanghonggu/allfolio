-- 반드시 백엔드 배포 "전"에 실행 (ddl-auto: none). 기존 행에 NULL이 들어가므로 무해. 멱등.
--
--
-- ## 왜 `area_pyeong`으로 안 되는가
--
-- 국토부 실거래가는 **전용면적을 ㎡로** 준다. `ua_assets`에는 `area_pyeong`(평)뿐인데,
-- 그 값으로는 실거래 행을 고를 수 없다. 단순히 단위가 달라서가 아니라 **무엇의 면적인지가
-- 안 갈리기 때문**이다.
--
-- 등록 화면의 라벨은 `면적 (평)` 하나이고 예시는 `30`이다. 전용인지 공급인지 아무 데도
-- 적혀 있지 않다. 한국에서 "34평"은 보통 공급면적을 뜻하고, 그 집의 전용면적은 84㎡ =
-- 약 25.4평이다. 같은 숫자 "34"를 전용으로 읽으면 **한 평형 위 단지의 실거래가**를 가져온다.
--
--     사용자 입력 "34"  →  공급 34평 ≈ 전용 84㎡   (맞음)
--                      →  전용 34평 ≈ 전용 112㎡  (한 평형 위, 값이 수억 차이)
--
-- 둘 다 그럴듯한 금액이라 **화면으로는 틀린 걸 알 수 없다.** 금에서 돈(3.75g)을 g로 읽으면
-- 3.75배가 되던 것과 같은 종류이고, 그때의 해법도 같았다 — **단위를 추측하지 않는다.**
--
--
-- ## 그래서 매칭 키를 따로 둔다
--
-- `area_pyeong`은 **사용자가 적은 값 그대로**, 표시용으로 남긴다. 뜻이 모호하므로 매칭에
-- 쓰지 않는다. 이 컬럼은 **소스가 확정한 전용면적**만 담는다 — R2 선택 UI에서 사용자가
-- 단지·평형을 고르면 API가 준 값이 그대로 들어오고, 그때부터 모호성이 없다.
--
-- 둘을 한 컬럼으로 합치지 않는 이유가 이것이다. 합치면 "사용자가 적은 모르는 값"과
-- "소스가 확정한 값"이 구분되지 않고, 매칭이 전자를 만나는 순간 조용히 틀린다.
--
--
-- ## nullable인 이유
--
-- 아파트가 아닌 부동산(빌라·단독·토지)과 선택 UI 이전에 등록된 자산에는 이 값이 없다.
-- **`area_pyeong`에서 환산해 채우지 말 것** — 위 이유로 그 환산은 근거가 없다.
-- 값이 없으면 자동 평가를 하지 않는 것이 맞다(설계 원칙: 산출 불가능하면 null).
--
--
-- ## 단지 식별은 `symbol`이 맡는다
--
-- 컬럼을 새로 만들지 않는다. `ua_assets.symbol`은 이미 자유 문자열이고 STOCK·CRYPTO가
-- 티커를 담는 자리다. 부동산은 실거래 상세자료의 **단지일련번호**(`11110-2339` 형태)를
-- 담는다. 두 값이 같은 컬럼에 있어도 `type`이 다르므로 섞이지 않는다.
--
--
-- ## 인덱스를 만들지 않는다
--
-- 이 컬럼으로 조회하는 경로가 없다. 평가 배치는 `type`으로 고르고, 매칭은 이미 읽은 행에서
-- 꺼낸 값으로 캐시를 뒤진다.

ALTER TABLE ua_assets ADD COLUMN IF NOT EXISTS exclusive_area_m2 NUMERIC(10,4);

COMMENT ON COLUMN ua_assets.exclusive_area_m2 IS
    '전용면적(㎡). 실거래가 매칭 키 — 소스가 확정한 값만 들어간다. area_pyeong(사용자 입력, 전용/공급 불명)에서 환산해 채우지 말 것';

-- ── 검증 ────────────────────────────────────────────────────────────────────
-- 부동산 자산이 몇 건인지, 그중 면적을 적은 건 몇 건인지 센다.
-- **이 숫자가 R2의 규모다** — 기존 자산이 많으면 선택 UI로 다시 고르게 할 안내가 필요하고,
-- 0건이면 그냥 새 등록 경로만 만들면 된다.
SELECT
    type,
    count(*)                                          AS assets,
    count(*) FILTER (WHERE area_pyeong IS NOT NULL)   AS has_pyeong,
    count(*) FILTER (WHERE exclusive_area_m2 IS NOT NULL) AS has_exclusive,
    count(*) FILTER (WHERE symbol IS NOT NULL)        AS has_symbol
FROM ua_assets
WHERE type IN ('REAL_ESTATE', 'JEONSE')
GROUP BY type
ORDER BY type;
